def _esc(text: str) -> str:
    return html.escape(text, quote=True)


def _keyframes(name: str, stops: list[tuple[float, str]]) -> str:
    merged: dict[float, str] = {}
    for pct, props in stops:
        merged[round(min(100.0, max(0.0, pct)), 3)] = props
    body = "".join(f"{p}%{{{props}}}" for p, props in sorted(merged.items()))
    return f"@keyframes {name}{{{body}}}"


def build_css(layout: Layout) -> str:
    n = layout.n_steps
    total = layout.total_seconds
    pct = lambda seconds: seconds * 100.0 / total  # noqa: E731
    rules = [
        "text{font-family:-apple-system,'Segoe UI',Roboto,Helvetica,Arial,sans-serif}",
        ".nd{stroke-width:1.6}",
        f".ed{{fill:none;stroke:{EDGE_COLOR};stroke-width:2;stroke-linecap:round;"
        "stroke-dasharray:1 1;stroke-dashoffset:0}",
        ".ed.bk{stroke:%s}" % BACK_EDGE_COLOR,
        ".cp{opacity:0}",
        ".pk{opacity:0}",
        ".ex{font-family:ui-monospace,SFMono-Regular,Menlo,Consolas,monospace}",
    ]
    frames: list[str] = []
    anim: list[str] = []
    dim = "opacity:.22"
    for k in range(n):
        a = k * STEP_SECONDS
        settle = (k + 1) * STEP_SECONDS
        end_hold = total * 0.97
        frames.append(
            _keyframes(
                f"nd{k}",
                [
                    (0, f"{dim};stroke-width:1.6"),
                    (pct(a), f"{dim};stroke-width:1.6"),
                    (pct(a + 0.4), "opacity:1;stroke-width:4"),
                    (pct(min(settle, end_hold)), "opacity:1;stroke-width:1.6"),
                    (pct(end_hold), "opacity:1;stroke-width:1.6"),
                    (100, f"{dim};stroke-width:1.6"),
                ],
            )
        )
        frames.append(
            _keyframes(
                f"ed{k}",
                [
                    (0, "stroke-dashoffset:1;opacity:0"),
                    (pct(a), "stroke-dashoffset:1;opacity:0"),
                    (pct(a) + 0.01, "stroke-dashoffset:1;opacity:1"),
                    (pct(a + DRAW_SECONDS), "stroke-dashoffset:0;opacity:1"),
                    (pct(end_hold), "stroke-dashoffset:0;opacity:1"),
                    (100, "stroke-dashoffset:1;opacity:0"),
                ],
            )
        )
        frames.append(
            _keyframes(
                f"ar{k}",
                [
                    (0, "opacity:0"),
                    (pct(a + DRAW_SECONDS * 0.8), "opacity:0"),
                    (pct(a + DRAW_SECONDS), "opacity:1"),
                    (pct(end_hold), "opacity:1"),
                    (100, "opacity:0"),
                ],
            )
        )
        frames.append(
            _keyframes(
                f"pk{k}",
                [
                    (0, "opacity:0"),
                    (pct(a), "opacity:0"),
                    (pct(a) + 0.01, "opacity:1"),
                    (pct(a + DRAW_SECONDS), "opacity:1"),
                    (pct(a + DRAW_SECONDS + 0.25), "opacity:0"),
                    (100, "opacity:0"),
                ],
            )
        )
        last = k == n - 1
        frames.append(
            _keyframes(
                f"cp{k}",
                [
                    (0, "opacity:0"),
                    (pct(a), "opacity:0"),
                    (pct(a + 0.35), "opacity:1"),
                    (pct(end_hold if last else settle - 0.15), "opacity:1"),
                    (pct(end_hold if last else settle), "opacity:%s" % ("1" if last else "0")),
                    (100, "opacity:0"),
                ],
            )
        )
        for sel, kf in ((f".nd.s{k}", f"nd{k}"), (f".ed.s{k}", f"ed{k}"), (f".ar.s{k}", f"ar{k}"),
                        (f".pk.s{k}", f"pk{k}"), (f".cp.s{k}", f"cp{k}")):
            anim.append(f"{sel}{{animation:{kf} {total:.2f}s linear infinite}}")
    motion = "@media (prefers-reduced-motion:no-preference){" + "".join(anim) + "}"
    return "".join(rules) + "".join(frames) + motion


def _packet_svg(g: EdgeGeom, layout: Layout) -> str:
    """A dot riding the tip of the edge while it draws: the example moving through the system."""
    total = layout.total_seconds
    t0 = g.step * STEP_SECONDS / total
    t1 = (g.step * STEP_SECONDS + DRAW_SECONDS) / total
    if t0 <= 0:
        points, times = "0;1;1", f"0;{t1:.4f};1"
    else:
        points, times = "0;0;1;1", f"0;{t0:.4f};{t1:.4f};1"
    return (
        f'<circle class="pk s{g.step}" r="{PACKET_R}" fill="{ACCENT}" stroke="#ffffff" stroke-width="2">'
        f'<animateMotion dur="{total:.2f}s" repeatCount="indefinite" calcMode="linear" '
        f'keyPoints="{points}" keyTimes="{times}" path="{g.path_d()}"/></circle>'
    )


def render_svg(layout: Layout) -> str:
    spec = layout.spec
    W, H = layout.width, layout.height
    out: list[str] = []
    add = out.append
    desc = " ".join(f"{i + 1}. {s.caption}" for i, s in enumerate(spec.steps))
    add(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" role="img" '
        f'aria-label="{_esc(spec.title or "Diagram")}" '
        f'style="width:100%;max-width:{W}px;height:auto;display:block;margin:0 auto">'
    )
    add(f"<title>{_esc(spec.title or 'Diagram')}</title><desc>{_esc(desc)}</desc>")
    add(f"<style>{build_css(layout)}</style>")
    add(
        f'<rect width="{W}" height="{H}" rx="14" fill="{CARD_FILL}" stroke="{CARD_STROKE}"/>'
    )
    if spec.title:
        add(f'<text x="{PAD}" y="34" font-size="17" font-weight="700" fill="{TEXT_DARK}">'
            f"{_esc(spec.title)}</text>")
    if spec.caption:
        add(f'<text x="{PAD}" y="53" font-size="12" fill="{TEXT_MUTED}">{_esc(spec.caption)}</text>')

    add(f'<g transform="translate({layout.ox:.1f},{layout.oy:.1f})">')
    for name, gx, gy, gw, gh in layout.groups:
        add(
            f'<rect x="{gx:.1f}" y="{gy:.1f}" width="{gw:.1f}" height="{gh:.1f}" rx="12" '
            f'fill="#e2e8f0" fill-opacity=".45" stroke="#cbd5e1" stroke-dasharray="5 4"/>'
            f'<text x="{gx + 10:.1f}" y="{gy + 16:.1f}" font-size="11" font-weight="600" '
            f'fill="{TEXT_MUTED}">{_esc(name)}</text>'
        )
    for g in layout.edges:
        cls = f"ed s{g.step}" + (" bk" if g.back else "")
        add(f'<path class="{cls}" pathLength="1" d="{g.path_d()}"/>')
    for g in layout.edges:
        pts = " ".join(f"{x:.1f},{y:.1f}" for x, y in g.arrow)
        color = BACK_EDGE_COLOR if g.back else EDGE_COLOR
        add(f'<polygon class="ar s{g.step}" points="{pts}" fill="{color}"/>')
        if g.edge.label:
            lx, ly = g.label_pos
            add(
                f'<text class="ar s{g.step}" x="{lx:.1f}" y="{ly:.1f}" font-size="11" '
                f'text-anchor="middle" fill="{TEXT_MUTED}" stroke="{CARD_FILL}" stroke-width="4" '
                f'paint-order="stroke">{_esc(g.edge.label)}</text>'
            )
    for g in layout.edges:
        add(_packet_svg(g, layout))
    for p in layout.placed.values():
        fill, stroke = KIND_COLORS[p.node.kind]
        step = layout.node_step[p.node.id]
        add(f'<g class="nd s{step}">')
        if p.node.novel:
            add(
                f'<rect x="{p.x - 4:.1f}" y="{p.y - 4:.1f}" width="{p.w + 8:.0f}" height="{p.h + 8:.0f}" '
                f'rx="13" fill="none" stroke="{ACCENT}" stroke-opacity=".28" stroke-width="3"/>'
            )
            stroke = ACCENT
        add(
            f'<rect x="{p.x:.1f}" y="{p.y:.1f}" width="{p.w:.0f}" height="{p.h:.0f}" rx="10" '
            f'fill="{fill}" stroke="{stroke}"/>'
        )
        tag = p.novel_tag()
        if tag:
            tx, ty, tw, th = tag
            add(
                f'<rect x="{tx:.1f}" y="{ty:.1f}" width="{tw}" height="{th}" rx="{th / 2}" fill="{ACCENT}"/>'
                f'<text x="{tx + tw / 2:.1f}" y="{ty + th - 4:.1f}" font-size="{NOVEL_TAG[1]}" '
                f'font-weight="700" letter-spacing=".6" text-anchor="middle" fill="#ffffff">{NOVEL_TAG[0]}</text>'
            )
        box = p.example_box()
        if box:
            bx, by, bw, bh = box
            add(f'<g class="ar s{step}">')
            add(
                f'<rect x="{bx:.1f}" y="{by:.1f}" width="{bw:.0f}" height="{bh:.0f}" rx="6" '
                f'fill="{CHIP_FILL}" stroke="{KIND_COLORS[p.node.kind][1]}" stroke-opacity=".45"/>'
            )
            for text, ty in p.example_rows():
                add(
                    f'<text class="ex" x="{p.cx:.1f}" y="{ty:.1f}" font-size="{EXAMPLE_SIZE}" '
                    f'text-anchor="middle" fill="{TEXT_DARK}">{_esc(text)}</text>'
                )
            add("</g>")
        for text, ty, is_label in p.text_rows():
            if is_label:
                add(
                    f'<text x="{p.cx:.1f}" y="{ty:.1f}" font-size="{LABEL_SIZE}" '
                    f'font-weight="700" text-anchor="middle" fill="{TEXT_DARK}">{_esc(text)}</text>'
                )
            else:
                add(
                    f'<text x="{p.cx:.1f}" y="{ty:.1f}" font-size="{DETAIL_SIZE}" '
                    f'text-anchor="middle" fill="{TEXT_MUTED}">{_esc(text)}</text>'
                )
        add("</g>")
    add("</g>")
    for k, step in enumerate(spec.steps):
        add(
            f'<text class="cp s{k}" x="{W / 2:.0f}" y="{H - 24}" font-size="14" '
            f'text-anchor="middle" fill="{TEXT_DARK}">'
            f'<tspan fill="{ACCENT}" font-weight="700">{k + 1}/{layout.n_steps}  </tspan>'
            f"{_esc(step.caption)}</text>"
        )
    add("</svg>")
    return "".join(out)


def render_flow_svg(raw_or_spec: Any) -> Optional[tuple[str, int]]:
    """Convenience: dict/FlowSpec -> (svg, iframe_height). None if unusable."""
    spec = raw_or_spec if isinstance(raw_or_spec, FlowSpec) else FlowSpec.from_raw(raw_or_spec)
    if spec is None:
        return None
    layout = layout_flow(spec)
    return render_svg(layout), int(layout.height) + 16

