"""Deterministic flow-diagram engine: normalise -> layout -> animated SVG.

The LLM only supplies *meaning* (nodes, edges, narrated steps). Geometry is
computed here, so diagrams never overlap, never depend on a model's idea of
pixel coordinates, and can be animated (and exported as a GIF, see ``gif.py``).

Everything that reaches the SVG is XML-escaped and ids are generated by us, so
the output is safe to embed even though the text originates from an LLM.
"""
