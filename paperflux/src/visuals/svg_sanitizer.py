"""Allowlist SVG sanitiser for *legacy* model-authored SVG.

New diagrams are generated by our own renderer (``flow.py``) and need none of
this. Older stored documents (and the odd model that still emits raw SVG) go
through here. Approach: parse as XML, keep only allowlisted elements and
attributes, fail closed on anything odd. Regex sanitisers are bypassable.
"""
from __future__ import annotations

import re
import xml.etree.ElementTree as ET
from typing import Optional

SVG_NS = "http://www.w3.org/2000/svg"
XLINK_NS = "http://www.w3.org/1999/xlink"
MAX_BYTES = 300_000

ALLOWED_TAGS = {
    "svg", "g", "defs", "symbol", "use", "title", "desc", "path", "rect", "circle",
    "ellipse", "line", "polyline", "polygon", "text", "tspan", "marker", "style",
    "lineargradient", "radialgradient", "stop", "clippath",
    "animate", "animatetransform", "animatemotion", "set", "mpath",
}
ANIMATION_TAGS = {"animate", "animatetransform", "animatemotion", "set"}
SAFE_ANIMATED_ATTRS = {
    "opacity", "fill", "fill-opacity", "stroke", "stroke-opacity", "stroke-width",
    "stroke-dashoffset", "stroke-dasharray", "transform", "r", "cx", "cy", "x", "y",
    "x1", "x2", "y1", "y2", "width", "height", "d", "points", "offset", "visibility",
}
ALLOWED_ATTRS = {
    "id", "class", "viewbox", "width", "height", "x", "y", "x1", "x2", "y1", "y2", "cx",
    "cy", "r", "rx", "ry", "d", "points", "transform", "fill", "fill-opacity",
    "fill-rule", "stroke", "stroke-width", "stroke-opacity", "stroke-linecap",
    "stroke-linejoin", "stroke-dasharray", "stroke-dashoffset", "opacity", "style",
    "font-family", "font-size", "font-weight", "font-style", "text-anchor",
    "dominant-baseline", "dx", "dy", "letter-spacing", "marker-start", "marker-mid",
    "marker-end", "markerwidth", "markerheight", "refx", "refy", "orient",
    "markerunits", "preserveaspectratio", "offset", "stop-color", "stop-opacity",
    "gradientunits", "gradienttransform", "fx", "fy", "clip-path", "patternunits",
    "xmlns", "pathlength", "href", "attributename", "attributetype", "from", "to",
    "by", "values", "begin", "dur", "end", "repeatcount", "repeatdur", "fill",
    "keytimes", "keysplines", "calcmode", "additive", "accumulate", "type", "rotate",
    "path", "role", "aria-label", "paint-order", "visibility", "display",
}
_BAD_VALUE = re.compile(r"(javascript:|data:|vbscript:|expression\s*\(|@import|behavior\s*:|-moz-binding)", re.I)
_URL = re.compile(r"url\(\s*([^)]*)\)", re.I)


def _local(tag: str) -> str:
    return tag.rsplit("}", 1)[-1].lower() if isinstance(tag, str) else ""


def _safe_value(value: str) -> bool:
    if _BAD_VALUE.search(value):
        return False
    for match in _URL.finditer(value):
        target = match.group(1).strip().strip("'\"")
        if not target.startswith("#"):
            return False
    return True


def _clean_css(css: str) -> str:
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    kept: list[str] = []
    for rule in re.split(r"(?<=})", css):
        if rule.strip() and _safe_value(rule) and "<" not in rule:
            kept.append(rule)
    return "".join(kept)


def _clean(el: ET.Element) -> bool:
    """Sanitise in place. Returns False if the element itself must be dropped."""
    tag = _local(el.tag)
    if tag not in ALLOWED_TAGS:
        return False

    if tag in ANIMATION_TAGS:
        target = (el.get("attributeName") or "").strip().lower()
        if target not in SAFE_ANIMATED_ATTRS:
            return False

    for name in list(el.attrib):
        local = name.rsplit("}", 1)[-1].lower()
        value = el.attrib[name]
        if local.startswith("on") or local not in ALLOWED_ATTRS:
            del el.attrib[name]
            continue
        if local == "href":
            if not value.strip().startswith("#"):
                del el.attrib[name]
            continue
        if local == "style":
            cleaned = _clean_css(value)
            if cleaned:
                el.set(name, cleaned)
            else:
                del el.attrib[name]
            continue
        if not _safe_value(value):
            del el.attrib[name]

    if tag == "style":
        el.text = _clean_css(el.text or "")
        for child in list(el):
            el.remove(child)
    else:
        el.text = el.text if el.text is None or "<" not in el.text else ""

    for child in list(el):
        if not _clean(child):
            el.remove(child)
    return True


def sanitize_svg(svg: str) -> str:
    """Return a safe SVG string, or "" if the input cannot be trusted."""
    if not svg:
        return ""
    text = svg.strip()
    if text.startswith("```"):
        text = re.sub(r"^```(?:svg|xml)?\s*", "", text)
        text = re.sub(r"\s*```$", "", text)
    if len(text.encode("utf-8", "ignore")) > MAX_BYTES:
        return ""
    lowered = text.lower()
    if "<!doctype" in lowered or "<!entity" in lowered or "<?xml-stylesheet" in lowered:
        return ""
    if "<svg" not in lowered:
        return ""
    # drop an XML prolog if present (ElementTree rejects it after whitespace)
    text = re.sub(r"^\s*<\?xml[^>]*\?>", "", text)
    ET.register_namespace("", SVG_NS)
    ET.register_namespace("xlink", XLINK_NS)
    try:
        root = ET.fromstring(text)
    except ET.ParseError:
        return ""
    if _local(root.tag) != "svg" or not _clean(root):
        return ""
    return ET.tostring(root, encoding="unicode")


def safe_svg_or_none(svg: str) -> Optional[str]:
    cleaned = sanitize_svg(svg)
    return cleaned or None
