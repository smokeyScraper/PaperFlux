def _clip(text: Any, limit: int) -> str:
    value = " ".join(str(text or "").split())
    if len(value) <= limit:
        return value
    return value[: limit - 1].rstrip() + "…"


def _truthy(value: Any) -> bool:
    if isinstance(value, str):
        return value.strip().lower() in {"true", "yes", "1", "new"}
    return value is True or value == 1


@dataclass
class Node:
    id: str
    label: str
    detail: str = ""
    kind: str = "process"
    group: str = ""
    novel: bool = False  # introduced by this paper (vs a standard component)
    example: str = ""  # the running example's value at this node, e.g. "196 x 768"


@dataclass
class Edge:
    src: str
    dst: str
    label: str = ""


@dataclass
class Step:
    caption: str
    nodes: list[str]


@dataclass
class FlowSpec:
    title: str
    caption: str
    nodes: list[Node]
    edges: list[Edge]
    steps: list[Step]
    warnings: list[str] = field(default_factory=list)

    # ---- construction -----------------------------------------------------
    @classmethod
    def from_raw(cls, raw: Any) -> Optional["FlowSpec"]:
        """Tolerant parser for model output. Returns None if unusable."""
        if not isinstance(raw, dict):
            return None
        warnings: list[str] = []

        nodes: list[Node] = []
        by_id: dict[str, Node] = {}
        by_label: dict[str, Node] = {}
        for index, item in enumerate(raw.get("nodes") or []):
            if isinstance(item, str):
                item = {"label": item}
            if not isinstance(item, dict):
                continue
            label = _clip(
                item.get("label") or item.get("name") or item.get("title"), MAX_LABEL
            )
            if not label:
                continue
            if len(nodes) >= MAX_NODES:
                warnings.append(f"Dropped nodes beyond the first {MAX_NODES}")
                break
            node_id = str(item.get("id") or f"n{index}").strip() or f"n{index}"
            if node_id in by_id:
                node_id = f"{node_id}_{index}"
            kind = str(item.get("kind") or "process").strip().lower()
            node = Node(
                id=node_id,
                label=label,
                detail=_clip(item.get("detail") or item.get("description"), MAX_DETAIL),
                kind=kind if kind in NODE_KINDS else "process",
                group=_clip(item.get("group"), 24),
                novel=_truthy(item.get("novel")),
                example=_clip(item.get("example"), MAX_EXAMPLE),
            )
            nodes.append(node)
            by_id[node_id] = node
            by_label.setdefault(label.lower(), node)

        if len(nodes) < 2:
            return None

        def resolve(ref: Any) -> Optional[str]:
            key = str(ref or "").strip()
            if key in by_id:
                return key
            found = by_label.get(key.lower())
            return found.id if found else None

        edges: list[Edge] = []
        seen_pairs: set[tuple[str, str]] = set()
        for item in raw.get("edges") or []:
            if not isinstance(item, dict):
                continue
            src = resolve(item.get("from", item.get("src", item.get("source"))))
            dst = resolve(item.get("to", item.get("dst", item.get("target"))))
            if not src or not dst or src == dst or (src, dst) in seen_pairs:
                continue
            seen_pairs.add((src, dst))
            edges.append(Edge(src, dst, _clip(item.get("label"), MAX_EDGE_LABEL)))

        if not edges:
            warnings.append("No valid edges; nodes were chained in order")
            edges = [Edge(a.id, b.id) for a, b in zip(nodes, nodes[1:])]

        steps: list[Step] = []
        for item in raw.get("steps") or []:
            if not isinstance(item, dict):
                continue
            ids: list[str] = []
            for ref in item.get("nodes") or item.get("active") or []:
                rid = resolve(ref)
                if rid and rid not in ids:
                    ids.append(rid)
            caption = _clip(
                item.get("caption") or item.get("title") or item.get("text"),
                MAX_CAPTION,
            )
            if ids and caption:
                steps.append(Step(caption, ids))
            if len(steps) >= MAX_STEPS:
                break

        spec = cls(
            title=_clip(raw.get("title"), MAX_TITLE),
            caption=_clip(raw.get("caption"), 110),
            nodes=nodes,
            edges=edges,
            steps=steps,
            warnings=warnings,
        )
        spec._complete_steps()
        return spec

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Optional["FlowSpec"]:
        return cls.from_raw(data)

    def to_dict(self) -> dict[str, Any]:
        return {
            "title": self.title,
            "caption": self.caption,
            "nodes": [
                {
                    "id": n.id,
                    "label": n.label,
                    "detail": n.detail,
                    "kind": n.kind,
                    "group": n.group,
                    "novel": n.novel,
                    "example": n.example,
                }
                for n in self.nodes
            ],
            "edges": [{"from": e.src, "to": e.dst, "label": e.label} for e in self.edges],
            "steps": [{"caption": s.caption, "nodes": list(s.nodes)} for s in self.steps],
        }

    def fingerprint(self) -> str:
        blob = json.dumps(self.to_dict(), sort_keys=True).encode("utf-8")
        return hashlib.sha1(blob).hexdigest()[:16]

    # ---- helpers ----------------------------------------------------------
    def _complete_steps(self) -> None:
        """Guarantee a story: derive steps from the graph if absent, and make
        sure every node is revealed at some point."""
        if not self.steps:
            layers = _assign_layers(self)[0]
            by_id = {n.id: n for n in self.nodes}
            for layer in layers:
                real = [nid for nid in layer if nid in by_id]
                if real:
                    caption = _clip(" + ".join(by_id[i].label for i in real), MAX_CAPTION)
                    self.steps.append(Step(caption, real))
            if len(self.steps) > MAX_STEPS:
                head = self.steps[: MAX_STEPS - 1]
                tail_nodes = [i for s in self.steps[MAX_STEPS - 1 :] for i in s.nodes]
                head.append(Step("Finally: " + _clip(
                    ", ".join(by_id[i].label for i in tail_nodes), 70), tail_nodes))
                self.steps = head
            return
        covered = {i for s in self.steps for i in s.nodes}
        missing = [n.id for n in self.nodes if n.id not in covered]
        if missing:
            self.steps[-1].nodes.extend(missing)


