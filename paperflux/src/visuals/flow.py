@dataclass
class Placed:
    node: Node
    x: float
    y: float
    w: float
    h: float
    layer: int
    label_lines: list[str]
    detail_lines: list[str]
    example_lines: list[str] = field(default_factory=list)

    @property
    def cx(self) -> float:
        return self.x + self.w / 2

    @property
    def cy(self) -> float:
        return self.y + self.h / 2

    def text_rows(self) -> list[tuple[str, float, bool]]:
        """(text, baseline_y, is_label) rows shared by the SVG and GIF renderers."""
        rows: list[tuple[str, float, bool]] = []
        ty = self.y + 12
        for i, line in enumerate(self.label_lines):
            ty += LABEL_SIZE if i == 0 else LABEL_LINE_H
            rows.append((line, ty, True))
        if self.detail_lines:
            ty += 4
            for line in self.detail_lines:
                ty += DETAIL_LINE_H
                rows.append((line, ty, False))
        return rows

    def example_box(self) -> Optional[tuple[float, float, float, float]]:
        """(x, y, w, h) of the value chip, or None when the node has no example."""
        if not self.example_lines:
            return None
        h = EXAMPLE_H + (len(self.example_lines) - 1) * DETAIL_LINE_H
        return self.x + 10, self.y + self.h - h - 8, self.w - 20, h

    def example_rows(self) -> list[tuple[str, float]]:
        box = self.example_box()
        if box is None:
            return []
        top = box[1] + 14
        return [(line, top + i * DETAIL_LINE_H) for i, line in enumerate(self.example_lines)]

    def novel_tag(self) -> Optional[tuple[float, float, float, float]]:
        """(x, y, w, h) of the NEW tag straddling the top-right border."""
        if not self.node.novel:
            return None
        _, _, w, h = NOVEL_TAG
        return self.x + self.w - w - 10, self.y - h / 2, w, h


@dataclass
class EdgeGeom:
    edge: Edge
    segments: list[tuple[tuple[float, float], ...]]  # cubic: p0, c1, c2, p1
    arrow: list[tuple[float, float]]
    label_pos: tuple[float, float]
    back: bool
    step: int = 0

    def path_d(self) -> str:
        first = self.segments[0][0]
        parts = [f"M{first[0]:.1f},{first[1]:.1f}"]
        for _, c1, c2, p1 in self.segments:
            parts.append(
                f"C{c1[0]:.1f},{c1[1]:.1f} {c2[0]:.1f},{c2[1]:.1f} {p1[0]:.1f},{p1[1]:.1f}"
            )
        return " ".join(parts)

    def polyline(self, samples: int = 16) -> list[tuple[float, float]]:
        pts: list[tuple[float, float]] = []
        for seg in self.segments:
            p0, c1, c2, p1 = seg
            for i in range(samples + 1):
                if pts and i == 0:
                    continue
                t = i / samples
                mt = 1 - t
                x = mt**3 * p0[0] + 3 * mt**2 * t * c1[0] + 3 * mt * t**2 * c2[0] + t**3 * p1[0]
                y = mt**3 * p0[1] + 3 * mt**2 * t * c1[1] + 3 * mt * t**2 * c2[1] + t**3 * p1[1]
                pts.append((x, y))
        return pts


@dataclass
class Layout:
    spec: FlowSpec
    width: float
    height: float
    ox: float
    oy: float
    horizontal: bool
    placed: dict[str, Placed]
    edges: list[EdgeGeom]
    groups: list[tuple[str, float, float, float, float]]
    node_step: dict[str, int]
    total_seconds: float

    @property
    def n_steps(self) -> int:
        return len(self.spec.steps)


def _text_w(text: str, size: float, bold: bool = False) -> float:
    return len(text) * size * (0.60 if bold else 0.55)


def _hard_split(word: str, max_chars: int) -> list[str]:
    return [word[i : i + max_chars] for i in range(0, len(word), max_chars)] or [word]


def wrap_text(text: str, size: float, max_w: float, bold: bool, max_lines: int) -> list[str]:
    if not text:
        return []
    max_chars = max(4, int(max_w / (size * (0.60 if bold else 0.55))))
    words: list[str] = []
    for word in text.split():
        words.extend(_hard_split(word, max_chars) if len(word) > max_chars else [word])
    lines: list[str] = []
    cur = ""
    for word in words:
        trial = f"{cur} {word}".strip()
        if cur and _text_w(trial, size, bold) > max_w:
            lines.append(cur)
            cur = word
        else:
            cur = trial
    if cur:
        lines.append(cur)
    if len(lines) > max_lines:
        lines = lines[:max_lines]
        last = lines[-1]
        while last and _text_w(last + "…", size, bold) > max_w:
            last = last[:-1]
        lines[-1] = last.rstrip() + "…"
    return lines


def _assign_layers(spec: FlowSpec) -> tuple[list[list[str]], set[int], dict[str, int]]:
    """Return (layers of node ids, indices of back edges, layer-of-node)."""
    ids = [n.id for n in spec.nodes]
    out: dict[str, list[int]] = {i: [] for i in ids}
    indeg = {i: 0 for i in ids}
    for ei, e in enumerate(spec.edges):
        out[e.src].append(ei)
        indeg[e.dst] += 1

    back: set[int] = set()
    state: dict[str, int] = {}

    def dfs(u: str) -> None:
        state[u] = 1
        for ei in out[u]:
            v = spec.edges[ei].dst
            if state.get(v, 0) == 1:
                back.add(ei)
            elif state.get(v, 0) == 0:
                dfs(v)
        state[u] = 2

    for nid in [i for i in ids if indeg[i] == 0] + ids:
        if state.get(nid, 0) == 0:
            dfs(nid)

    fwd = [(e.src, e.dst) for ei, e in enumerate(spec.edges) if ei not in back]
    layer = {i: 0 for i in ids}
    # longest-path layering over the (acyclic) forward graph
    for _ in range(len(ids)):
        changed = False
        for s, d in fwd:
            if layer[d] < layer[s] + 1:
                layer[d] = layer[s] + 1
                changed = True
        if not changed:
            break
    count = max(layer.values()) + 1
    layers: list[list[str]] = [[] for _ in range(count)]
    for nid in ids:
        layers[layer[nid]].append(nid)
    return layers, back, layer


def _order_layers(
    layers: list[list[str]], segments: list[tuple[str, str]]
) -> list[list[str]]:
    preds: dict[str, list[str]] = {}
    succs: dict[str, list[str]] = {}
    for a, b in segments:
        succs.setdefault(a, []).append(b)
        preds.setdefault(b, []).append(a)
    for _ in range(6):
        pos = {n: i for layer in layers for i, n in enumerate(layer)}
        for li in range(1, len(layers)):
            layers[li].sort(
                key=lambda n: (
                    sum(pos[p] for p in preds[n]) / len(preds[n]) if preds.get(n) else pos[n],
                    pos[n],
                )
            )
            pos = {n: i for layer in layers for i, n in enumerate(layer)}
        for li in range(len(layers) - 2, -1, -1):
            layers[li].sort(
                key=lambda n: (
                    sum(pos[s] for s in succs[n]) / len(succs[n]) if succs.get(n) else pos[n],
                    pos[n],
                )
            )
            pos = {n: i for layer in layers for i, n in enumerate(layer)}
    return layers


def _lane_ranks(spec: FlowSpec, chains: dict[int, list[str]]) -> dict[str, int]:
    """Lane per node for side-by-side comparisons ("Baseline" vs "This paper"): every node
    grouped, 2+ groups, and no edge between groups. Empty when the diagram is not one."""
    groups = list(dict.fromkeys(n.group for n in spec.nodes))
    if len(groups) < 2 or "" in groups:
        return {}
    group_of = {n.id: n.group for n in spec.nodes}
    if any(group_of[e.src] != group_of[e.dst] for e in spec.edges):
        return {}
    rank = {nid: groups.index(group) for nid, group in group_of.items()}
    for ei, chain in chains.items():
        for dummy in chain[1:-1]:
            rank[dummy] = rank[spec.edges[ei].src]
    return rank


def _node_size(node: Node) -> tuple[float, list[str], list[str], list[str]]:
    inner = NODE_W - 22
    label_lines = wrap_text(node.label, LABEL_SIZE, inner, True, 2)
    detail_lines = wrap_text(node.detail, DETAIL_SIZE, inner, False, 2)
    example_lines = wrap_text(node.example, EXAMPLE_SIZE, inner - 16, False, 2)
    h = 22 + len(label_lines) * LABEL_LINE_H
    if detail_lines:
        h += 6 + len(detail_lines) * DETAIL_LINE_H
    if example_lines:
        h += 10 + EXAMPLE_H + (len(example_lines) - 1) * DETAIL_LINE_H
    return max(54.0, float(h)), label_lines, detail_lines, example_lines


def layout_flow(spec: FlowSpec) -> Layout:
    layers, back_idx, layer_of = _assign_layers(spec)
    horizontal = len(layers) <= MAX_LAYERS_LR

    # chains for long forward edges -> dummy nodes so routes avoid other nodes
    chains: dict[int, list[str]] = {}
    segments: list[tuple[str, str]] = []
    for ei, e in enumerate(spec.edges):
        if ei in back_idx:
            continue
        chain = [e.src]
        for k, li in enumerate(range(layer_of[e.src] + 1, layer_of[e.dst])):
            dummy = f"~{ei}.{k}"
            layers[li].append(dummy)
            chain.append(dummy)
        chain.append(e.dst)
        chains[ei] = chain
        segments.extend(zip(chain, chain[1:]))
    layers = _order_layers(layers, segments)

    by_id = {n.id: n for n in spec.nodes}
    sizes: dict[str, tuple[float, float]] = {}
    lines: dict[str, tuple[list[str], list[str], list[str]]] = {}
    for nid, node in by_id.items():
        h, ll, dl, el = _node_size(node)
        sizes[nid] = (NODE_W, h)
        lines[nid] = (ll, dl, el)

    def size(n: str) -> tuple[float, float]:
        return sizes.get(n, (0.0, float(DUMMY)))

    def flow_ext(n: str) -> float:
        w, h = size(n)
        return w if horizontal else h

    def cross_ext(n: str) -> float:
        w, h = size(n)
        return h if horizontal else w

    gap_flow = GAP_FLOW_LR if horizontal else GAP_FLOW_TB
    gap_cross = GAP_CROSS_LR if horizontal else GAP_CROSS_TB

    def run_ext(members: list[str]) -> float:
        return sum(cross_ext(n) for n in members) + gap_cross * max(0, len(members) - 1)

    lane_rank = _lane_ranks(spec, chains)
    n_lanes = max(lane_rank.values()) + 1 if lane_rank else 1

    def lane_members(layer: list[str], lane: int) -> list[str]:
        return [n for n in layer if lane_rank.get(n, 0) == lane]

    lane_ext = [max(run_ext(lane_members(layer, k)) for layer in layers) for k in range(n_lanes)]
    lane_start: list[float] = []
    acc = 0.0
    for ext in lane_ext:
        lane_start.append(acc)
        acc += ext + LANE_GAP
    total_cross = acc - LANE_GAP

    layer_ext = [max(flow_ext(n) for n in layer) for layer in layers]
    flow_pos: list[float] = []
    acc = 0.0
    for ext in layer_ext:
        flow_pos.append(acc)
        acc += ext + gap_flow
    total_flow = acc - gap_flow

    centers: dict[str, tuple[float, float]] = {}
    placed: dict[str, Placed] = {}
    for li, layer in enumerate(layers):
        for lane in range(n_lanes):
            members = lane_members(layer, lane)
            v = lane_start[lane] + (lane_ext[lane] - run_ext(members)) / 2
            for nid in members:
                u = flow_pos[li] + (layer_ext[li] - flow_ext(nid)) / 2
                w, h = size(nid)
                x, y = (u, v) if horizontal else (v, u)
                centers[nid] = (x + w / 2, y + h / 2)
                if nid in by_id:
                    placed[nid] = Placed(by_id[nid], x, y, w, h, li, *lines[nid])
                v += cross_ext(nid) + gap_cross

    content_w = total_flow if horizontal else total_cross
    content_h = total_cross if horizontal else total_flow

    # ---- anchors with spread so fan-in / fan-out edges do not stack ----------
    out_edges: dict[str, list[tuple[float, int]]] = {}
    in_edges: dict[str, list[tuple[float, int]]] = {}
    for ei, chain in chains.items():
        nxt = centers[chain[1]]
        prv = centers[chain[-2]]
        out_edges.setdefault(chain[0], []).append((nxt[1] if horizontal else nxt[0], ei))
        in_edges.setdefault(chain[-1], []).append((prv[1] if horizontal else prv[0], ei))

    def spread(table: dict[str, list[tuple[float, int]]]) -> dict[tuple[str, int], float]:
        offsets: dict[tuple[str, int], float] = {}
        for nid, items in table.items():
            items.sort()
            span = cross_ext(nid) * 0.55
            step = min(14.0, span / max(1, len(items)))
            for rank, (_, ei) in enumerate(items):
                offsets[(nid, ei)] = (rank - (len(items) - 1) / 2) * step
        return offsets

    out_off = spread(out_edges)
    in_off = spread(in_edges)

    def anchor(nid: str, side: str, off: float) -> tuple[float, float]:
        p = placed[nid]
        if horizontal:
            return (p.x + p.w, p.cy + off) if side == "out" else (p.x, p.cy + off)
        return (p.cx + off, p.y + p.h) if side == "out" else (p.cx + off, p.y)

    def cubic(p0: tuple[float, float], p1: tuple[float, float]) -> tuple[tuple[float, float], ...]:
        if horizontal:
            dx = (p1[0] - p0[0]) * 0.5
            return (p0, (p0[0] + dx, p0[1]), (p1[0] - dx, p1[1]), p1)
        dy = (p1[1] - p0[1]) * 0.5
        return (p0, (p0[0], p0[1] + dy), (p1[0], p1[1] - dy), p1)

    node_step = _node_steps(spec)
    geoms: list[EdgeGeom] = []
    back_count = 0
    for ei, e in enumerate(spec.edges):
        step = max(node_step[e.src], node_step[e.dst])
        if ei in chains:
            chain = chains[ei]
            pts = [anchor(chain[0], "out", out_off[(chain[0], ei)])]
            pts += [centers[c] for c in chain[1:-1]]
            pts.append(anchor(chain[-1], "in", in_off[(chain[-1], ei)]))
            segs = [cubic(a, b) for a, b in zip(pts, pts[1:])]
            tip = pts[-1]
            arrow = (
                [tip, (tip[0] - 9, tip[1] - 5), (tip[0] - 9, tip[1] + 5)]
                if horizontal
                else [tip, (tip[0] - 5, tip[1] - 9), (tip[0] + 5, tip[1] - 9)]
            )
            geom = EdgeGeom(e, segs, arrow, (0, 0), False, step)
            mid = geom.polyline()[len(geom.polyline()) // 2]
            geom.label_pos = (mid[0], mid[1] - 7) if horizontal else (mid[0] + 8, mid[1])
        else:
            s, d = placed[e.src], placed[e.dst]
            channel = 36 + 13 * back_count
            back_count += 1
            if horizontal:
                bottom = content_h + channel
                p0 = (s.cx, s.y + s.h)
                p1 = (d.cx, d.y + d.h)
                seg = (p0, (p0[0], bottom), (p1[0], bottom), p1)
                arrow = [p1, (p1[0] - 5, p1[1] + 9), (p1[0] + 5, p1[1] + 9)]
                label = ((p0[0] + p1[0]) / 2, bottom - 4)
            else:
                right = content_w + channel
                p0 = (s.x + s.w, s.cy)
                p1 = (d.x + d.w, d.cy)
                seg = (p0, (right, p0[1]), (right, p1[1]), p1)
                arrow = [p1, (p1[0] + 9, p1[1] - 5), (p1[0] + 9, p1[1] + 5)]
                label = (right + 6, (p0[1] + p1[1]) / 2)
            geom = EdgeGeom(e, [seg], arrow, label, True, step)
        geoms.append(geom)

    extra = 36 + 13 * back_count if back_count else 0
    if horizontal:
        content_h += extra
    else:
        content_w += extra

    # ---- optional group boxes (skipped when they would swallow a stranger) ---
    groups: list[tuple[str, float, float, float, float]] = []
    names = sorted({n.group for n in spec.nodes if n.group})
    for name in names:
        members = [placed[n.id] for n in spec.nodes if n.group == name]
        if len(members) < 2:
            continue
        gx0 = min(m.x for m in members) - 12
        gy0 = min(m.y for m in members) - 26
        gx1 = max(m.x + m.w for m in members) + 12
        gy1 = max(m.y + m.h for m in members) + 12
        clash = any(
            p.node.group != name
            and not (p.x + p.w < gx0 or p.x > gx1 or p.y + p.h < gy0 or p.y > gy1)
            for p in placed.values()
        )
        if not clash:
            groups.append((name, gx0, gy0, gx1 - gx0, gy1 - gy0))
    top_pad = (26 if groups else 0) + (NOVEL_TAG[3] / 2 + 2 if any(n.novel for n in spec.nodes) else 0)

    width = max(MIN_W, content_w + 2 * PAD)
    height = HEADER + top_pad + content_h + FOOTER
    total_seconds = len(spec.steps) * STEP_SECONDS + HOLD_SECONDS
    return Layout(
        spec=spec,
        width=math.ceil(width),
        height=math.ceil(height),
        ox=(width - content_w) / 2,
        oy=HEADER + top_pad,
        horizontal=horizontal,
        placed=placed,
        edges=geoms,
        groups=groups,
        node_step=node_step,
        total_seconds=total_seconds,
    )


def _node_steps(spec: FlowSpec) -> dict[str, int]:
    out: dict[str, int] = {}
    for k, step in enumerate(spec.steps):
        for nid in step.nodes:
            out.setdefault(nid, k)
    last = max(0, len(spec.steps) - 1)
    for n in spec.nodes:
        out.setdefault(n.id, last)
    return out


